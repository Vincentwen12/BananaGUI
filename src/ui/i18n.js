let current = 'zh';

export function setLanguage(language) {
  current = language === 'en' ? 'en' : 'zh';
  try {
    localStorage.setItem('banana-language', current);
  } catch {
    // 忽略
  }
  document.documentElement.lang = current === 'en' ? 'en' : 'zh-CN';
  window.dispatchEvent(new CustomEvent('banana-language', { detail: { language: current } }));
}

export function getLanguage() {
  try {
    const saved = localStorage.getItem('banana-language');
    if (saved === 'en' || saved === 'zh') current = saved;
  } catch {
    // 忽略
  }
  return current;
}

export function t(key) {
  return STRINGS[current]?.[key] ?? STRINGS.zh[key] ?? key;
}
